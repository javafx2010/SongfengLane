"""卷一 1-6 章定点回改：红线句（支持亲生结论）与她段称谓（冬生→他/弟弟）。幂等可重跑。"""
import io, re, sys

BASE = r'章节/卷一_大学保研'

def rep(path, pairs):
    t = io.open(path, encoding='utf-8').read()
    n = 0
    for old, new in pairs:
        if old in t:
            t = t.replace(old, new, 1)
            n += 1
    io.open(path, 'w', encoding='utf-8', newline='\n').write(t)
    print(path.split('\\')[-1], 'applied', n, '/', len(pairs))

f5 = BASE + r'/第005章_巷子里的十二年/第005章_巷子里的十二年.md'
rep(f5, [
    # 细纲：不写结论字样
    ('父亲手里其实有两张纸：另一张，女儿那一栏写着「支持亲生」——1996年他就算明白的事，这回白纸黑字。这张他锁进抽屉，一辈子没拿出来。',
     '父亲手里其实有两张纸：另一张是省城的那份，1996年冬他就把那一栏算明白了，这回白纸黑字落了印。这张他只看了一遍就锁进抽屉，一辈子没拿出来——正文不写那一栏印的是什么字，只写他看了多久、锁在哪里。'),
    # 正文：真鉴定不出现结论字样
    ('报告写得很简单，一页纸。女儿那一栏，印着三个字：支持亲生。',
     '报告写得很简单，一页纸。女儿那一栏就在第三行，一行字。'),
    # 正文：贴身口袋那张纸
    ('收的时候，他贴身口袋里那张纸硌了一下——就是那张写着支持亲生的纸。他隔着棉袄按了按，按平了。',
     '收的时候，他贴身口袋里那张纸硌了一下。他隔着棉袄按了按，按平了。'),
    # 她段称谓
    ('搪瓷缸给了冬生喝水的用', '搪瓷缸给了弟弟喝水的用'),
    ('每天晚上，冬生睡了，她把堂屋的灯拉亮', '每天晚上，弟弟睡了，她把堂屋的灯拉亮'),
    ('弟弟冬生那年六岁，他把筷子数了一遍', '弟弟那年六岁，他把筷子数了一遍'),
    ('弟弟冬生的书包是新的', '弟弟的书包是新的'),
    ('胖丫没说，冬生没说，母亲跟前也没提', '胖丫没说，弟弟没说，母亲跟前也没提'),
])

f6 = BASE + r'/第006章_十八岁的巷口/第006章_十八岁的巷口.md'
rep(f6, [
    ('冬生凑过来，说：姐，你的信纸。她回了一句：书包里。冬生嗯了一声，走了。',
     '弟弟凑过来，说：姐，你的信纸。她回了一句：书包里。他嗯了一声，走了。'),
])

# 复检
print('---- 复检 ----')
for n in range(1, 7):
    fs = [p for p in __import__('glob').glob(BASE + r'/第00%d章_*/第00%d章_*.md' % (n, n))]
    for f in fs:
        t = io.open(f, encoding='utf-8').read()
        body = t.split('## 正文', 1)[-1]
        bad = [m for m in re.finditer('支持亲生', body) if body[max(0, m.start()-1):m.start()] != '不']
        seg = t.split('＊　＊　＊', 1)[1] if '＊　＊　＊' in t else ''
        if bad:
            print('仍违规-支持亲生:', f.split('\\')[-1], len(bad))
        if '冬生' in seg:
            print('她段仍含冬生:', f.split('\\')[-1])
print('复检完成')
